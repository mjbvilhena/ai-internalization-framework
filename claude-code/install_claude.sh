#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROMPT_SOURCE="$SCRIPT_DIR/../core/internalize_prompt.md"

if [[ $# -eq 0 ]] || [[ "$1" == "--global" ]]; then
    SKILLS_DIR="$HOME/.claude/skills"
    echo "Installing globally for Claude Code..."
else
    SKILLS_DIR="$1/.claude/skills"
    echo "Installing to the project at $1..."
fi

SKILL_DIR="$SKILLS_DIR/internalize"
SKILL_FILE="$SKILL_DIR/SKILL.md"

echo "Installing Claude Code Internalization Skill to $SKILL_FILE..."
mkdir -p "$SKILL_DIR"

# Generate the frontmatter
cat << 'FRONTMATTER' > "$SKILL_FILE"
---
name: internalize
description: Run the internalization protocol to understand, map and retain a project that was heavily generated by AI. Use when the user asks to internalize a project, folder, concept or document, or to deep-review a single file chunk by chunk.
argument-hint: "[standard | deep review <file>] [focus]"
---

FRONTMATTER

# Append the core prompt
cat "$PROMPT_SOURCE" >> "$SKILL_FILE"

LEGACY_WRAPPER="$HOME/.local/bin/cl-internalize"
if [[ -f "$LEGACY_WRAPPER" ]]; then
    echo "Note: $LEGACY_WRAPPER comes from an earlier version of this installer and no longer works."
    echo "Remove it with: rm \"$LEGACY_WRAPPER\" && rm -r \"$HOME/.config/cl-internalize\""
fi

echo "✅ Successfully installed."
echo "Start Claude Code in a project and type /internalize, or ask it to \"internalize this project\"."
